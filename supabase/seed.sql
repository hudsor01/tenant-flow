-- The previous 468-line version could never have served the test suites, and it
-- aborted `supabase start` / `db reset` outright:
--
--   1. It inserted into `tenants.user_id`, a column dropped on 2026-06-16 by
--      20260616161248_drop_dead_tenants_user_id. Any reset failed there.
--   2. It created a DIFFERENT cast -- test-admin@tenantflow.app, owner-a@test.com,
--      owner-b@test.com, tenant-a@test.com, tenant-b@test.com (8 references) --
--      while every suite reads E2E_OWNER_{EMAIL,PASSWORD},
--      E2E_OWNER_B_{EMAIL,PASSWORD} and E2E_ADMIN_{EMAIL,PASSWORD}
--      (tests/integration/rls/*.test.ts, tests/e2e/auth-helpers.ts:273,
--      tests/e2e/dashboard-rpc-helpers.ts:49). It referenced the `e2e-` cast
--      zero times.
--   3. It wrote auth rows by hand with crypt() and created ZERO
--      `auth.identities` rows, so the password grant had no identity to match
--      and sign-in could not succeed regardless. Measured 2026-10-25: the
--      Admin-API path produces exactly 1 identity per user, which is what makes
--      sign-in work.
--   4. It never set `is_admin` or `subscription_status`, so a seeded owner would
--      have failed the proxy's subscription gate and landed on /pricing
--      (tests/e2e/auth-helpers.ts:328 fails loudly on exactly that).
