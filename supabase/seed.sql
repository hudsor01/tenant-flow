-- Seeding auth users from SQL is the wrong layer: GoTrue owns `auth.users` and
-- `auth.identities`, and hand-written inserts drift from whatever schema it
-- expects. scripts/seed-test-users.ts uses `auth.admin.createUser` instead,
-- refuses to run against a non-loopback host, and verifies each pair with a real
-- sign-in before reporting success.
--
-- Keep this file present and empty rather than deleting it: `[db.seed]` in
-- config.toml lists `./seed.sql` in `sql_paths`, and a missing path is an error.
